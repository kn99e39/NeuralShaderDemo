"""Build one BMW Garage XL variant from the untouched BMW27 file.

blender --factory-startup -b --python build_xl.py -- <protocol.json> <bays_per_side> <instanced|realized> <out.blend> <manifest.json>

Construction (protocol `xl_policy`):
  * bay (0,0) is the original scene, untouched: front car (real objects),
    rear car (collection instance `1M`, the mover), emission panel `Light`;
  * every other bay (i,j) adds, at offset (i*pitch, j*pitch, 0):
      - a front-car copy  = collection instance of `1M` at instance_offset + O,
      - a rear-car copy   = collection instance of `1M` at the mover's G0
                            location + O with the mover's rotation,
      - a panel copy      = linked duplicate of `Light` at its location + O;
  * the cyclorama `Floor` is scaled in x/y (z unchanged) and recentred so the
    grid keeps the original margin;
  * `realized` converts the added collection instances into real objects
    (duplicates_make_real), so their evaluated geometry is no longer shared;
  * camera `XLCamera` copies the original camera data, keeps its azimuth,
    looks down at `elevation_deg`, uses `lens_mm`, and is placed at the
    smallest distance that frames every car's bounding box.
No material, shader, light strength, world or render setting is changed.
"""

from __future__ import annotations

import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bench_common as B  # noqa: E402
import bpy  # noqa: E402
from bpy_extras.object_utils import world_to_camera_view  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402


def front_car_bbox(depsgraph, mover_name: str, exclude: set):
    """World bbox of every mesh instance not generated by the mover (= the front car)."""
    pts = []
    for oi in depsgraph.object_instances:
        o = oi.object
        if o.type != "MESH" or o.original.name in exclude:
            continue
        if oi.is_instance and oi.parent and oi.parent.original.name == mover_name:
            continue
        pts += [oi.matrix_world @ Vector(c) for c in o.bound_box]
    return (Vector([min(p[k] for p in pts) for k in range(3)]),
            Vector([max(p[k] for p in pts) for k in range(3)]))


def main() -> None:
    protocol_path, g, mode, out_blend, manifest_path = B.script_args()[:5]
    g = int(g)
    protocol = B.load_protocol(protocol_path)
    xl = protocol["xl_policy"]
    src = protocol["scene_source"]["path"]
    bpy.ops.wm.open_mainfile(filepath=src, load_ui=False)
    scene = bpy.context.scene
    pitch = xl["bay_pitch_m"]
    coll = bpy.data.collections[protocol["mover"]["collection"]]
    mover = bpy.data.objects[protocol["mover"]["object"]]
    light = bpy.data.objects[xl["panel_object"]]
    floor = bpy.data.objects[xl["floor_object"]]
    xl_coll = bpy.data.collections.new("BMW_Garage_XL")
    scene.collection.children.link(xl_coll)

    dg = bpy.context.evaluated_depsgraph_get()
    front_lo, front_hi = front_car_bbox(dg, mover.name, {floor.name, light.name})
    off = Vector(coll.instance_offset)
    car_boxes = [("bay0_front", front_lo, front_hi)]
    # Rear car box from its instance transform applied to the front car's box.
    rear_m = mover.matrix_world @ Matrix.Translation(-off)
    car_boxes.append(("bay0_rear",) + _xf_box(rear_m, front_lo, front_hi))

    added = []
    for i in range(g):
        for j in range(g):
            if i == 0 and j == 0:
                continue
            o = Vector((i * pitch, j * pitch, 0.0))
            fa = bpy.data.objects.new(f"XL_front_{i}_{j}", None)
            fa.instance_type = "COLLECTION"
            fa.instance_collection = coll
            fa.location = off + o
            xl_coll.objects.link(fa)
            rb = bpy.data.objects.new(f"XL_rear_{i}_{j}", None)
            rb.instance_type = "COLLECTION"
            rb.instance_collection = coll
            rb.location = mover.location + o
            rb.rotation_euler = mover.rotation_euler
            xl_coll.objects.link(rb)
            lp = light.copy()  # linked duplicate: shares the panel mesh and material
            lp.name = f"XL_panel_{i}_{j}"
            lp.location = light.location + o
            xl_coll.objects.link(lp)
            added += [fa, rb]
            car_boxes.append((f"bay{i}{j}_front", front_lo + o, front_hi + o))
            rm = Matrix.Translation(o) @ rear_m
            car_boxes.append((f"bay{i}{j}_rear",) + _xf_box(rm, front_lo, front_hi))

    # Floor: keep the original margin around the grid.
    glo, ghi = _union(car_boxes)
    orig_lo, orig_hi = _union(car_boxes[:2])
    half0 = xl["floor_half_extent_m"]
    margin = half0 - max(orig_hi.x - orig_lo.x, orig_hi.y - orig_lo.y) / 2.0
    half = max(ghi.x - glo.x, ghi.y - glo.y) / 2.0 + margin
    s = max(1.0, half / half0)
    center = (glo + ghi) / 2.0
    orig_center = (orig_lo + orig_hi) / 2.0
    if g > 1:
        floor.scale = (floor.scale.x * s, floor.scale.y * s, floor.scale.z)
        floor.location = (floor.location.x + center.x - orig_center.x,
                          floor.location.y + center.y - orig_center.y, floor.location.z)

    if mode == "realized":
        bpy.ops.object.select_all(action="DESELECT")
        for e in added:
            e.select_set(True)
        bpy.context.view_layer.objects.active = added[0] if added else None
        if added:
            bpy.ops.object.duplicates_make_real(use_base_parent=False, use_hierarchy=True)
    elif mode != "instanced":
        raise ValueError(mode)

    cam = _place_camera(scene, xl, car_boxes, center)
    scene.camera = cam
    bpy.context.view_layer.update()
    vis = _visibility(scene, cam, car_boxes)

    os.makedirs(os.path.dirname(out_blend), exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=out_blend, relative_remap=True, compress=False, copy=True)
    manifest = {
        "variant": f"xl_{g}x{g}_{mode}",
        "bays_per_side": g, "mode": mode, "bays": g * g, "cars": 2 * g * g,
        "source_scene": src, "source_sha256": B.sha256(src),
        "out_blend": out_blend, "out_sha256": B.sha256(out_blend),
        "floor_scale_xy": s, "floor_location": list(floor.location),
        "grid_bbox": [list(glo), list(ghi)],
        "camera": {"name": cam.name, "location": list(cam.location),
                   "rotation_euler": list(cam.rotation_euler), "lens": cam.data.lens,
                   "focus_distance": cam.data.dof.focus_distance,
                   "fstop": cam.data.dof.aperture_fstop, "clip_end": cam.data.clip_end},
        "visibility": vis,
        "build_memory": B.process_memory_mb(),
        "environment": B.environment(),
    }
    B.R.dump_json(manifest, manifest_path)
    print("XL_DONE", out_blend, vis["cars_visible"], "/", vis["cars"], flush=True)


def _union(boxes):
    return (Vector([min(b[1][k] for b in boxes) for k in range(3)]),
            Vector([max(b[2][k] for b in boxes) for k in range(3)]))


def _xf_box(m, lo, hi):
    pts = [m @ Vector((x, y, z)) for x in (lo.x, hi.x) for y in (lo.y, hi.y) for z in (lo.z, hi.z)]
    return (Vector([min(p[k] for p in pts) for k in range(3)]),
            Vector([max(p[k] for p in pts) for k in range(3)]))


def _place_camera(scene, xl, car_boxes, center):
    src = scene.camera
    cam = bpy.data.objects.new("XLCamera", src.data.copy())
    scene.collection.objects.link(cam)
    cam.data.lens = xl["camera"]["lens_mm"]
    az = Vector((src.location.x - (car_boxes[0][1].x + car_boxes[0][2].x) / 2.0,
                 src.location.y - (car_boxes[0][1].y + car_boxes[0][2].y) / 2.0, 0.0)).normalized()
    el = math.radians(xl["camera"]["elevation_deg"])
    target = Vector((center.x, center.y, xl["camera"]["target_z_m"]))
    view_dir = Vector((az.x * math.cos(el), az.y * math.cos(el), math.sin(el)))  # target -> camera
    corners = [Vector((x, y, z)) for _, lo, hi in car_boxes
               for x in (lo.x, hi.x) for y in (lo.y, hi.y) for z in (lo.z, hi.z)]
    m = xl["camera"]["frame_margin"]

    def fits(d):
        cam.location = target + view_dir * d
        cam.rotation_euler = (-view_dir).to_track_quat("-Z", "Y").to_euler()
        bpy.context.view_layer.update()
        for p in corners:
            v = world_to_camera_view(scene, cam, p)
            if v.z <= 0 or not (m <= v.x <= 1 - m and m <= v.y <= 1 - m):
                return False
        return True

    lo_d, hi_d = 1.0, 2000.0
    if not fits(hi_d):
        raise RuntimeError("grid does not fit in frame")
    for _ in range(40):
        mid = 0.5 * (lo_d + hi_d)
        if fits(mid):
            hi_d = mid
        else:
            lo_d = mid
    fits(hi_d)
    cam.data.dof.focus_object = None
    cam.data.dof.focus_distance = hi_d
    cam.data.clip_end = max(cam.data.clip_end, 4.0 * hi_d)
    return cam


def _first_camera_visible_hit(scene, dg, origin, target):
    """scene.ray_cast ignores render visibility; step past objects hidden from camera rays
    (the emission panels are visible_camera=False in the original file)."""
    d = (target - origin).normalized()
    start = origin.copy()
    remaining = (target - origin).length + 1.0
    for _ in range(16):
        ok, loc, _n, _i, obj, _m = scene.ray_cast(dg, start, d, distance=remaining)
        if not ok:
            return None
        if obj.original.visible_camera:
            return loc
        step = (loc - start).length + 1e-3
        start = loc + d * 1e-3
        remaining -= step
    return None


def _visibility(scene, cam, car_boxes):
    """A car counts as visible if a camera ray to one of its 9 probe points hits inside its box."""
    dg = bpy.context.evaluated_depsgraph_get()
    origin = cam.matrix_world.translation
    visible = 0
    in_frame = 0
    per_car = []
    for name, lo, hi in car_boxes:
        c = (lo + hi) / 2.0
        probes = [c] + [c + 0.6 * (Vector((x, y, z)) - c)
                        for x in (lo.x, hi.x) for y in (lo.y, hi.y) for z in (lo.z, hi.z)]
        v = world_to_camera_view(scene, cam, c)
        if v.z > 0 and 0 <= v.x <= 1 and 0 <= v.y <= 1:
            in_frame += 1
        hits = 0
        for p in probes:
            loc = _first_camera_visible_hit(scene, dg, origin, p)
            if loc is not None and all(lo[k] - 0.05 <= loc[k] <= hi[k] + 0.05 for k in range(3)):
                hits += 1
        visible += hits > 0
        per_car.append([name, hits])
    return {"cars": len(car_boxes), "cars_center_in_frame": in_frame, "cars_visible": visible,
            "probe_hits_per_car": per_car}


if __name__ == "__main__":
    try:
        main()
    except Exception:
        import traceback
        traceback.print_exc()
        sys.stdout.flush()
        os._exit(1)
    sys.stdout.flush()
    os._exit(0)
